%EMPTYSUMMARY One QC summary row with every field present (NaN where unknown).
    s = struct('participant', string(participant), 'file', string(file), 'status', "failed", ...
        'n_samples', NaN, 'duration_min', NaN, 'sampling_hz', NaN, 'n_events', NaN, ...
        'n_START', NaN, 'n_BurnInStart', NaN, 'n_CueStart', NaN, 'n_CueFinish', NaN, ...
        'n_StimuliStart', NaN, 'n_RatingStart', NaN, 'n_BurnOutStart', NaN, ...
        'pupil_valid_fraction', NaN, 'gaze_valid_fraction', NaN, ...
        'cue_dur_min_s', NaN, 'cue_dur_mean_s', NaN, 'cue_dur_max_s', NaN, 'n_cue_off_setting', NaN, ...
        'countdown_min_s', NaN, 'countdown_mean_s', NaN, 'countdown_max_s', NaN, ...
        'n_malformed_lines', NaN, 'n_issues', NaN);
end
